	public static CultureInfo CurrentCulture { get; set; } = CultureInfo.CurrentUICulture;

	public static CultureInfo FallbackCulture { get; } = CultureInfo.GetCultureInfo("en");

	public static string GetString(string key)
	{
		return GetStringFor(key, CurrentCulture);
	}

	// The same lookup for an explicit culture, so a caller that was asked for a specific language
	// never has to switch the process-wide CurrentCulture to get it.
	public static string GetStringFor(string key, CultureInfo culture)
	{
		return TryGetPackValue(culture.TwoLetterISOLanguageName, key)
			?? TryGetPackValue(FallbackCulture.TwoLetterISOLanguageName, key)
			?? key;
	}

	public static string GetString(string key, params object[] args)
	{
		return string.Format(CultureInfo.CurrentCulture, GetString(key), args);
	}

	// A counted phrase: baseKey + ".One", ".Few" or ".Many", formatted with the count as {0}.
	// Every pack defines all three (key parity); a language without a distinction repeats a form.
	public static string GetPlural(string baseKey, int count)
	{
		return GetString(baseKey + "." + PluralCategory(CurrentCulture.TwoLetterISOLanguageName, count), count);
	}

	// ru: 1, 21, 31 -> One; 2-4, 22-24 -> Few; 0, 5-20, 25-30, 11-14 -> Many.
	// en (and any other language): 1 -> One, else Many.
	internal static string PluralCategory(string language, int count)
	{
		int n = Math.Abs(count);
		if (!string.Equals(language, "ru", StringComparison.OrdinalIgnoreCase))
		{
			return n == 1 ? "One" : "Many";
		}

		int last = n % 10;
		int lastTwo = n % 100;
		return last == 1 && lastTwo != 11 ? "One"
			: last is >= 2 and <= 4 && lastTwo is < 12 or > 14 ? "Few"
			: "Many";
	}

	// The localized value, or null when no pack (current or fallback) defines the key. Used where
	// a missing key must fall back to something other than the key itself (error-code phrases).
	public static string? TryGetString(string key)
	{
		return TryGetPackValue(CurrentCulture.TwoLetterISOLanguageName, key)
			?? TryGetPackValue(FallbackCulture.TwoLetterISOLanguageName, key);
	}

	// Read-only view of one language pack, for the key/placeholder parity tests.
	internal static IReadOnlyDictionary<string, string>? PackFor(string culture)
	{
		return Packs.TryGetValue(culture, out IReadOnlyDictionary<string, string>? pack) ? pack : null;
	}

	private static string? TryGetPackValue(string culture, string key)
	{
		return !Packs.TryGetValue(culture, out IReadOnlyDictionary<string, string>? pack)
			? null
			: pack.TryGetValue(key, out string? value) ? value : null;
	}
